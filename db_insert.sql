
DROP TABLE BOOKING_CONNECT_FLIGHT CASCADE CONSTRAINTS;
DROP TABLE BOOKING CASCADE CONSTRAINTS;
DROP TABLE FLIGHT CASCADE CONSTRAINTS;
DROP TABLE CUSTOMER CASCADE CONSTRAINTS;

CREATE TABLE CUSTOMER(
Customer_ID VARCHAR(20),
Name VARCHAR(20) NOT NULL,
Nationality VARCHAR(20) NOT NULL,
Passport_no VARCHAR(8) NOT NULL,
PRIMARY KEY(Customer_ID)
);


CREATE TABLE FLIGHT(
Flight_No VARCHAR(5),
Depart DATE NOT NULL,
Arrive DATE NOT NULL,
Fare INTEGER NOT NULL,
Seat_Limit INTEGER NOT NULL,
Source VARCHAR(20) NOT NULL,
Dest VARCHAR(20) NOT NULL,
PRIMARY KEY(Flight_No),
CHECK (Arrive > Depart),
CHECK (Source != Dest),
CHECK (Seat_Limit >= 0)
);

CREATE TABLE BOOKING(
Booking_id VARCHAR(20),
Num_flight INTEGER ,
Total_fare INTEGER ,
Customer_ID VARCHAR(20),
PRIMARY KEY(Booking_id),
FOREIGN KEY(Customer_ID) REFERENCES CUSTOMER,
CHECK ( Num_flight  BETWEEN 1 AND 3 )
);

CREATE TABLE BOOKING_CONNECT_FLIGHT(
Booking_id VARCHAR(20),
Flight_No VARCHAR(5),
Connect_order INTEGER,
PRIMARY KEY (Booking_id,Flight_No),
FOREIGN KEY(Booking_id) REFERENCES BOOKING ON DELETE CASCADE,
FOREIGN KEY(Flight_No) REFERENCES FLIGHT,
CHECK (Connect_order BETWEEN 1 AND 3)
);

