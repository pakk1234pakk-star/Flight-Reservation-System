CREATE OR REPLACE TRIGGER trg_check_seats_before_insert
BEFORE INSERT ON BOOKING_CONNECT_FLIGHT
FOR EACH ROW
DECLARE
    v_remaining INTEGER;
BEGIN
    SELECT Seat_Limit INTO v_remaining 
    FROM FLIGHT
    WHERE Flight_No = :NEW.Flight_No;

    IF ( v_remaining <= 0) THEN
RAISE_APPLICATION_ERROR(-20001, 'Flight ' || :NEW.Flight_No || ' is full');
    END IF;
END;
/

CREATE OR REPLACE TRIGGER trg_booking_decrease_seats
AFTER INSERT ON BOOKING_CONNECT_FLIGHT
FOR EACH ROW
BEGIN
    UPDATE FLIGHT
    SET Seat_Limit = Seat_Limit - 1
    WHERE Flight_No = :NEW.Flight_No;
END;
/

CREATE OR REPLACE TRIGGER trg_cancel_increase_seats
AFTER DELETE ON BOOKING_CONNECT_FLIGHT
FOR EACH ROW
BEGIN
    UPDATE FLIGHT
    SET Seat_Limit = Seat_Limit + 1
    WHERE Flight_No = :OLD.Flight_No;
END;
/

COMMIT;




